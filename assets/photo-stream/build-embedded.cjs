// Rebuild the file:// entry from the existing source. No dependencies required.
const fs=require('node:fs');
const path=require('node:path');
const files=['math','photos','shaders','lightfall','stories','gl','catalog','galaxy','story','app'];
const source=files.map(name=>{
  let code=fs.readFileSync(path.join(__dirname,'js',name+'.js'),'utf8');
  code=code.replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
  // Both modules use the same preference; share the app's declaration in this flat bundle.
  if(name==='story')code=code.replace(/^const REDUCED = .*;\r?\n/m,'');
  return code;
}).join('\n');
let html=fs.readFileSync(path.join(__dirname,'template.html'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'style.css'),'utf8');
html=html.replace('<link rel="stylesheet" href="./style.css">',()=>'<style>'+css+'</style>');
html=html.replace('<!-- PHOTO_STREAM_SCRIPT -->',()=>'<script>\n(()=>{\n'+source.replace(/<\/script/gi,'<\\/script')+'\n})();\n</script>');
const output='// Generated by build-embedded.cjs; edit js/, style.css or template.html, then rebuild.\nwindow.TravelPhotoStreamDocument='+JSON.stringify(html)+';\n';
fs.writeFileSync(path.join(__dirname,'embedded.js'),output);
console.log('Built embedded.js ('+Buffer.byteLength(output)+' bytes)');
